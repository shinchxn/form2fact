check('14.4 Central reviewer sees only own-tenant dockets',
  centralList.status === 200 && (centralList.json?.data || []).every(a => a.organizationId === 'org-aicte-central'));

// ------------------------------------------- 15. RBAC on destructive ops
const viewerLogin = await api('/api/v1/auth/login', { method: 'POST', body: { email: 'meenakshi.s@audit.gov.in', password: 'Auditor123!' } });
const viewerToken = viewerLogin.json?.token;

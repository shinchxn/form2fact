/**
 * Form2Fact — End-to-End Application Validation (Phase 9)
 *
 * Exercises the REAL application over HTTP against a running dev server:
 *   login → docket creation → PDF upload → extraction → validation →
 *   findings → LIVE AI explanation (BharatCode qwen-3.8-27b) →
 *   LIVE deep-scrutiny advisory → human review → audit trail →
 *   ledger integrity → tenant isolation → authorization checks.
 *
 * Uses synthetic sample documents only (sample_documents/).
 * Live model calls are budgeted: exactly one explanation + one deep-scrutiny memo.
 * If the model API is unavailable the step is reported as BLOCKED (never faked).
 *
 * Usage: node scripts/e2e-validation.mjs  (server must be running on :3000)
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const BASE = process.env.E2E_BASE || 'http://localhost:3000';
const SAMPLES_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'sample_documents');

let pass = 0, fail = 0, blocked = 0;
const results = [];
function check(name, ok, detail = '') {
  if (ok) { pass++; results.push(`PASS  ${name}`); console.log(`✅ ${name}${detail ? ' — ' + detail : ''}`); }
  else if (detail === 'BLOCKED') { blocked++; results.push(`BLOCK ${name}`); console.log(`⚠️  ${name} (BLOCKED)`); }
  else { fail++; results.push(`FAIL  ${name}${detail ? ' — ' + detail : ''}`); console.log(`❌ ${name}${detail ? ' — ' + detail : ''}`); }
}

async function api(path, { method = 'GET', token, body, raw } = {}) {
  const headers = {};
  if (token) headers['Authorization'] = `Bearer ${token}`;
  if (body && !(body instanceof FormData)) headers['Content-Type'] = 'application/json';
  const res = await fetch(BASE + path, {
    method,
    headers,
    body: body instanceof FormData ? body : body ? JSON.stringify(body) : undefined
  });
  if (raw) return res;
  let json = null;
  try { json = await res.json(); } catch { /* non-JSON */ }
  return { status: res.status, json };
}

console.log(`\n=== Form2Fact E2E Validation against ${BASE} ===\n`);

// ---------------------------------------------------------------- 1. health
const health = await api('/api/v1/health');
check('1.1 Public health endpoint', health.status === 200 && health.json?.status === 'ok', `v${health.json?.version}`);

// ------------------------------------------- 2. security contract (new)
const usersUnauth = await api('/api/v1/users');
check('2.1 Unauthenticated /users rejected (no enumeration)', usersUnauth.status === 401, `HTTP ${usersUnauth.status}`);

const personaUnauth = await api('/api/v1/user', { method: 'POST', body: { id: 'usr-002' } });
check('2.2 Unauthenticated persona switch rejected (no anonymous JWT minting)', personaUnauth.status === 401, `HTTP ${personaUnauth.status}`);

const appsUnauth = await api('/api/v1/applications');
check('2.3 Unauthenticated /applications rejected', appsUnauth.status === 401, `HTTP ${appsUnauth.status}`);

// ---------------------------------------------------------------- 3. login
const login = await api('/api/v1/auth/login', {
  method: 'POST',
  body: { email: 'vk.sharma@scrutiny.edu.in', password: 'Admin123!' }
});
check('3.1 Administrator login', login.status === 200 && login.json?.token, `user=${login.json?.user?.displayName}`);
const admin = login.json?.user;
const adminToken = login.json?.token;
check('3.2 Login response excludes passwordHash', login.json?.user && !('passwordHash' in login.json.user));

// ------------------------------------------------- 4. login rate limiting
let rateLimited = false;
for (let i = 0; i < 12; i++) {
  const r = await api('/api/v1/auth/login', { method: 'POST', body: { email: 'e2e-ratelimit-probe@form2fact.test', password: 'wrong-password-' + i } });
  if (r.status === 429) { rateLimited = true; break; }
}
check('4.1 Login rate limiting returns 429 after burst', rateLimited);

// ---------------------------------------------------------------- 5. docket
const created = await api('/api/v1/applications', {
  method: 'POST',
  token: adminToken,
  body: {
    institutionName: 'E2E Validation Institute of Technology',
    applicationType: 'New Institution',
    declaredDetails: {
      institutionName: 'E2E Validation Institute of Technology',
      societyOrTrustName: 'E2E Validation Trust',
      address: 'Plot 7, Knowledge Park, Bengaluru',
      pinCode: '560001',
      state: 'Karnataka',
      landAreaAcres: 12.5,
      leaseExpiryDate: '2035-06-30',
      sanctionedIntake: 180
    }
  }
});
check('5.1 Create application docket', created.status === 201 && created.json?.data?.id, created.json?.data?.referenceNumber);
const appId = created.json?.data?.id;

// ------------------------------------------------------- 6. document upload
// Synthetic lease deed (fictional; generated by scripts/make_e2e_sample_pdf.py)
// with deterministic extraction targets: 9.2 Acres + expiring 31/03/2035.
const leaseBuf = fs.readFileSync(path.join(SAMPLES_DIR, 'E2E_Synthetic_Lease_Deed.pdf'));
const form = new FormData();
form.append('file', new Blob([leaseBuf], { type: 'application/pdf' }), 'E2E_Synthetic_Lease_Deed.pdf');
form.append('documentType', 'Land Lease Deed');
const up1 = await api(`/api/v1/applications/${appId}/documents`, { method: 'POST', token: adminToken, body: form });
check('6.1 Upload lease deed PDF (synthetic sample)', up1.status === 201 && up1.json?.data?.processingStatus === 'Extracted',
  `pages=${up1.json?.data?.pageCount} status=${up1.json?.data?.processingStatus} checksum=${up1.json?.data?.checksum}`);

const docId = up1.json?.data?.id;

// rejected upload: non-PDF magic bytes
const badForm = new FormData();
badForm.append('file', new Blob([new TextEncoder().encode('not a pdf at all')], { type: 'application/pdf' }), 'fake.pdf');
badForm.append('documentType', 'Land Lease Deed');
const upBad = await api(`/api/v1/applications/${appId}/documents`, { method: 'POST', token: adminToken, body: badForm });
check('6.2 Non-PDF upload rejected via magic-byte verification', upBad.status === 400, `HTTP ${upBad.status}`);

// ------------------------------------------------------------ 7. extraction
const fields = await api(`/api/v1/documents/${docId}/fields`, { token: adminToken });
const fieldList = fields.json?.data || [];
check('7.1 Structured fields extracted with page + snippet + confidence',
  fields.status === 200 && fieldList.length > 0 &&
  fieldList.every(f => f.pageNumber && f.confidence > 0 && (f.sourceText || '').length > 0),
  `${fieldList.length} field(s): ${fieldList.map(f => f.fieldName).join(', ')}`);
const areaField = fieldList.find(f => f.fieldName === 'landAreaAcres');
const expiryField = fieldList.find(f => f.fieldName === 'leaseExpiryDate');
check('7.2 Extracted values are correct (9.2 Acres; 31/03/2035)',
  areaField?.normalizedValue === '9.2' && Boolean(expiryField),
  `area=${areaField?.rawValue ?? 'n/a'} (${areaField?.normalizedValue ?? '-'}) expiry=${expiryField?.rawValue ?? 'n/a'}`);

// ----------------------------------------------------------- 8. validation
const val = await api(`/api/v1/applications/${appId}/validate`, { method: 'POST', token: adminToken });
const appDetail = await api(`/api/v1/applications/${appId}`, { token: adminToken });
const findings = appDetail.json?.data?.findings || [];
check('8.1 Validation run produces evidence-linked findings or passes',
  val.status === 200 && findings.length >= 0, `${findings.length} finding(s)`);

// --------------------------------------------------- 9. pairwise endpoint
const pairwise = await api('/api/v1/verification/pairwise', {
  method: 'POST',
  token: adminToken,
  body: {
    claimField: { fieldName: 'landAreaAcres', fieldLabel: 'Declared Campus Area', rawValue: '12.5 Acres' },
    evidenceField: { fieldName: 'landAreaAcres', fieldLabel: 'Leased Area', rawValue: '9.2 Acres', documentName: 'Apex_Registered_Lease_Deed_Compliant.pdf', pageNumber: 1, sourceText: 'The demised premises measure 9.2 Acres.' },
    comparisonType: 'numeric'
  }
});
check('9.1 Pairwise classifier: numeric deficit → MISMATCH + human review',
  pairwise.status === 200 && pairwise.json?.data?.label === 'MISMATCH' && pairwise.json?.data?.requiresHumanReview === true,
  `label=${pairwise.json?.data?.label} conf=${pairwise.json?.data?.confidence} source=${pairwise.json?.data?.inferenceSource}`);

// ------------------------------------------------- 10. LIVE AI explanation
let explainResult = null;
if (findings.length > 0) {
  const f0 = findings.find(f => f.evidenceValue) || findings[0];
  explainResult = await api(`/api/v1/findings/${f0.id}/explain`, { method: 'POST', token: adminToken, body: {} });
  const r = explainResult.json || {};
  if (r.success) {
    check('10.1 LIVE AI explanation from qwen-3.8-27b (evidence-grounded)',
      r.modelUsed === 'qwen-3.8-27b' && r.data?.summary && r.data?.classification_context,
      `model=${r.modelUsed} label=${r.data.classification_context} latency=${r.latencyMs}ms requires_human_review=${r.data.requires_human_review}`);
    console.log(`     summary: ${String(r.data.summary).slice(0, 220)}`);
  } else {
    check('10.1 LIVE AI explanation from qwen-3.8-27b', false, 'BLOCKED', `${r.status}: ${r.error}`);
  }
} else {
  check('10.1 LIVE AI explanation from qwen-3.8-27b', false, 'BLOCKED', 'no findings generated to explain');
}

// --------------------------------------------- 11. LIVE deep scrutiny memo
const scrutiny = await api(`/api/v1/applications/${appId}/deep-scrutiny`, { method: 'POST', token: adminToken, body: {} });
const memo = scrutiny.json?.data;
if (memo?.isAiGenerated) {
  check('11.1 LIVE deep-scrutiny advisory memo (provider chain active)',
    /qwen-3.8-27b/i.test(memo.modelUsed) && memo.summary.length > 50,
    `model=${memo.modelUsed}`);
  console.log(`     memo: ${String(memo.summary).slice(0, 220)}`);
  check('11.2 Advisory memo carries human-review governance notice',
    /human|review|advisory|authoritative/i.test(memo.uncertaintyNotice || ''));
} else {
  check('11.1 LIVE deep-scrutiny advisory memo (provider chain active)', false, 'BLOCKED',
    `isAiGenerated=${memo?.isAiGenerated} model=${memo?.modelUsed}`);
}

// --------------------------------------------------- 12. human review + audit
let reviewCheck = 'no findings to review';
if (findings.length > 0) {
  const f1 = findings[0];
  const review = await api(`/api/v1/findings/${f1.id}/review`, {
    method: 'POST',
    token: adminToken,
    body: { action: 'Confirm', newStatus: 'Confirmed', note: 'E2E adjudication: variance verified against source lease deed page 1; discrepancy confirmed for record.' }
  });
  check('12.1 Reviewer records adjudicated finding status', review.status === 200 && review.json?.data?.status === 'Confirmed');
  const audit = await api(`/api/v1/applications/${appId}/audit`, { token: adminToken });
  const hasReviewEvent = (audit.json?.data || []).some(e => /review|finding|confirm/i.test(e.action || '') && e.actorId === admin.id);
  check('12.2 Audit ledger records the review action', hasReviewEvent, `${audit.json?.data?.length} audit event(s) for docket`);
}

const noNote = findings.length > 0 ? await api(`/api/v1/findings/${findings[0].id}/review`, {
  method: 'POST', token: adminToken, body: { action: 'Confirm', newStatus: 'Confirmed', note: '' }
}) : { status: 200 };
check('12.3 Review without written rationale rejected', findings.length === 0 || noNote.status === 400);

// ------------------------------------------------------------ 13. ledger
const ledger = await api('/api/v1/ledger/verify', { token: adminToken });
const led = ledger.json?.data || {};
check('13.1 Cryptographic audit ledger chain verifies',
  ledger.status === 200 && led.isValid === true && (led.tamperedEventsCount === 0) && led.brokenLinkIndex === null,
  `events=${led.totalEventsVerified} genesis=${led.genesisHashVerified} tampered=${led.tamperedEventsCount}`);

// -------------------------------------------------- 14. tenant isolation
const loginCentral = await api('/api/v1/auth/login', { method: 'POST', body: { email: 'rajesh.verma@scrutiny.edu.in', password: 'Reviewer123!' } });
const centralToken = loginCentral.json?.token;
check('14.1 Central-district reviewer login', Boolean(centralToken), loginCentral.json?.user?.organizationId);
